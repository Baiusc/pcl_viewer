void hex_to_string(char *tag, uint8_t *buf, int datalen)
{
	if (log_get_level() > LOG_DEBUG) {
		return;
	}

	char *str_buf = (char *)Malloc(datalen * 3);
	if (str_buf == NULL) {
		return;
	}

	for (int k = 0, j = 0; k < datalen; k++) {
		if (((buf[k] >> 4) & 0xf) > 9) {
			str_buf[j++] = ((buf[k] >> 4) & 0xf) - 10 + 'a';
		} else {
			str_buf[j++] = ((buf[k] >> 4) & 0xf) + '0';
		}

		if ((buf[k] & 0xf) > 9) {
			str_buf[j++] = (buf[k] & 0xf) - 10 + 'a';
		} else {
			str_buf[j++] = (buf[k] & 0xf) + '0';
		}

		str_buf[j++] = ' ';
	}
	str_buf[datalen * 3 - 1] = '\0';

	if (tag != NULL) {
		log_debug("[%s]: %s", tag, str_buf);
	} else {
		log_debug("%s", str_buf);
	}
	free(str_buf);
	str_buf = NULL;
}

bool is_power_of_two(uint32_t num)
{
	return (num != 0 && ((num & (num - 1)) == 0));
}

int roundup_pow_of_two(int num)
{
	if (num == 0) {
		return 0;
	}

	int pos = 0;
	for (int i = num; i != 0; i >>= 1) {
		pos++;
	}

	return (1 << pos);
}

void *Memcpy(void *dest, const void *src, size_t count)
{
	// 按 unsigned int (通常 4 字节) 为单位进行拷贝
	size_t words = count / sizeof(unsigned int);
	size_t bytes_remainder = count % sizeof(unsigned int);

	// 判断内存是否重叠以及拷贝方向
	if (dest <= src || (char *)dest >= (char *)src + count) {
		// 不重叠或目标在源之前：从前往后拷贝
		unsigned int *d = (unsigned int *)dest;
		const unsigned int *s = (const unsigned int *)src;

		// 按字长拷贝
		for (size_t i = 0; i < words; i++) {
			*d++ = *s++;
		}

		// 剩余字节按字节拷贝
		char *d_byte = (char *)d;
		const char *s_byte = (const char *)s;
		for (size_t i = 0; i < bytes_remainder; i++) {
			*d_byte++ = *s_byte++;
		}
	} else {
		// 内存重叠且目标在源之后：从后往前拷贝
		char *d_end = (char *)dest + count;
		const char *s_end = (const char *)src + count;

		// 剩余字节先从后往前拷贝
		for (size_t i = 0; i < bytes_remainder; i++) {
			*(--d_end) = *(--s_end);
		}

		// 然后按字长从后往前拷贝
		unsigned int *d_word = (unsigned int *)d_end - 1;
		const unsigned int *s_word = (const unsigned int *)s_end - 1;
		for (size_t i = 0; i < words; i++) {
			*d_word-- = *s_word--;
		}
	}

	return dest;
}

int16_t uint16_to_float_positive_number(int16_t num)
{
	// 提取符号位 - 0 为 正数，1 为负数
	int sign = (num >> 15) & 0x1;
	// 提取整数部分（中间的 8 位）
	int integer_part = (num >> 7) & 0xFF;

	if (sign) {
		integer_part = -integer_part;
	}

	return integer_part;
}
