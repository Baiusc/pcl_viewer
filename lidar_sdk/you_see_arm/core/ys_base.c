void Free(void **ptr)
{
	if (ptr == NULL || *ptr == NULL) {
		return;
	}

	free(*ptr);
	*ptr = NULL;
	return;
}

uint16_t crc16_checkout(const uint8_t *data, int length)
{
	unsigned char uchCRCHi = 0xff;
	unsigned char uchCRCLo = 0xff;
	unsigned int uindex;
	while (length--) {
		uindex = uchCRCHi ^ *data++;
		uchCRCHi = uchCRCLo ^ auchCRCHi[uindex];
		uchCRCLo = auchCRCLo[uindex];
	}
	return (uchCRCHi << 8 | uchCRCLo);
}

uint32_t crc32_checkout(const uint8_t *data, int length)
{
	uint32_t crc = 0xFFFFFFFF;
	for (int i = 0; i < length; ++i) {
		crc ^= data[i];
		for (int j = 0; j < 8; ++j) {
			crc = (crc >> 1) ^ ((crc & 1) * CRC32_POLYNOMIAL);
		}
	}
	return ~crc;
}

long long get_milliseconds_timestamp()
{
	struct timespec te;
	clock_gettime(CLOCK_REALTIME, &te); // 获取当前时间
	long long milliseconds = te.tv_sec * 1000LL + te.tv_nsec / 1000000; // 计算毫秒时间戳
	return milliseconds;
}

long long get_microseconds_timestamp()
{
	struct timespec ts;
	clock_gettime(CLOCK_MONOTONIC, &ts); // 获取当前时间
	long long microseconds = ts.tv_sec * 1000000LL + ts.tv_nsec / 1000; // 计算微秒时间戳
	return microseconds;
}

