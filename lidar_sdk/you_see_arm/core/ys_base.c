/**
 * @description  : check cpu endianness
 * @return        {int} result
 * 		0: is little endian
 * 		1: is big endian
 */
static int check_cpu_endianness()
{
	union {
		unsigned int value;
		unsigned char bytes[4];
	} test;

	test.value = 0x01020304;

	// 如果是小端序，最低有效字节 (LSB) 将存储在最低地址
	// 如果是大端序，最高有效字节 (MSB) 将存储在最低地址
	if (test.bytes[0] == 0x04) {
		return 0; // 小端序
	} else {
		return 1; // 大端序
	}
}

/**
 * @description  : reverse uint8 endianness
 * @param         {uint8_t} *data
 * @param         {int} num
 * @return        {*}
 */
static void reverse_uint8(uint8_t *data, int num)
{
	int i, j;
	uint8_t temp;

	for (i = 0, j = num - 1; i < j; i++, j--) {
		temp = data[i];
		data[i] = data[j];
		data[j] = temp;
	}
}

void transform_uint32_to_uint8(uint32_t value, uint8_t *result)
{
	result[0] = (value >> 0) & 0xFF;
	result[1] = (value >> 8) & 0xFF;
	result[2] = (value >> 16) & 0xFF;
	result[3] = (value >> 24) & 0xFF;

	// 大端序需要转小端序
	if (check_cpu_endianness()) {
		reverse_uint8(result, 4);
	}
}

void transform_int16_to_uint8(short value, uint8_t *result)
{
	result[0] = (value >> 0) & 0xFF;
	result[1] = (value >> 8) & 0xFF;

	// 大端序需要转小端序
	if (check_cpu_endianness()) {
		reverse_uint8(result, 2);
	}
}

