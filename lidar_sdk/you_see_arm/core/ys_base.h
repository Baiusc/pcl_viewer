/**
 * @description  : transform four uint8 to one float(little endian)
 * @param         {uint8_t} *data
 * @return        {float} float
 */
static inline float transform_uint8_to_float(const uint8_t *data)
{
	uint32_t lw;
	memcpy(&lw, data, sizeof(uint32_t));

	float_union_t fu = { .u32 = lw };
	return fu.f;
}

/**
 * @description  : transform four uint32 to one float(little endian)
 * @param         {uint32_t} data
 * @return        {float} float
 */
static inline float transform_uint32_to_float(const uint32_t data)
{
	float_union_t fu = { .u32 = data };
	return fu.f;
}

/**
 * @description  : transform one float to four uint8(little endian)
 * @param         {float} value
 * @param         {uint8_t *} result
 * @return        {void}
 */
static inline void transform_float_to_uint8(float value, uint8_t *result)
{
	float_union_t fu;
	fu.f = value;

	// Copy the bytes of fu.u32 into result in little endian order
	result[0] = (fu.u32 >> 0) & 0xFF;
	result[1] = (fu.u32 >> 8) & 0xFF;
	result[2] = (fu.u32 >> 16) & 0xFF;
	result[3] = (fu.u32 >> 24) & 0xFF;
	return;
}

