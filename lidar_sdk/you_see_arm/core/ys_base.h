/**
 * @description  : combine two uint8 to one uint16
 * @param         {uint8_t} high_byte
 * @param         {uint8_t} low_byte
 * @return        {uint16_t} result
 */
static inline uint16_t combine_uint8_to_uint16(uint8_t high_byte, uint8_t low_byte)
{
	return (uint16_t)(((uint16_t)high_byte << 8) | (uint16_t)low_byte);
}

/**
 * @description  : combine four uint8 to one uint32
 * @param         {uint8_t} byte1
 * @param         {uint8_t} byte2
 * @param         {uint8_t} byte3
 * @param         {uint8_t} byte4
 * @return        {uint32_t} result
 */
static inline uint32_t combine_uint8_to_uint32(uint8_t byte1, uint8_t byte2, uint8_t byte3, uint8_t byte4)
{
	return (uint32_t)(((uint32_t)byte1 << 24) | ((uint32_t)byte2 << 16) | ((uint32_t)byte3 << 8) | (uint32_t)byte4);
}

